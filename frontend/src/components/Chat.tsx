import { useEffect, useRef, useState } from 'react';
import { Bot, FileSearch, Info, Loader2, SendHorizonal, User } from 'lucide-react';
import { ask, type AskResult } from '../api';

interface Turn {
  id: number;
  question: string;
  result?: AskResult;
  error?: string;
}

function Sources({ result }: { result: AskResult }) {
  if (!result.sources.length) return null;
  return (
    <ol className="mt-3 space-y-2" aria-label="Sources">
      {result.sources.map((s) => (
        <li key={`${s.document_id}-${s.chunk}`} className="rounded-lg border border-ink-700 bg-ink-950/60 p-3 text-sm">
          <p className="flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-fog-400">
            <span className="font-mono text-accent-300">[{s.n}]</span>
            <span className="text-fog-200">{s.document}</span>
            {s.page !== null && <span>· page {s.page}</span>}
            {s.semantic_score !== null && <span title="Cosine similarity of local embeddings">· similarity {s.semantic_score.toFixed(2)}</span>}
            {s.matched_terms.length > 0 && <span>· terms: {s.matched_terms.join(', ')}</span>}
          </p>
          <p className="mt-1.5 leading-relaxed text-fog-200">{s.excerpt}</p>
          <details className="mt-1">
            <summary className="cursor-pointer text-xs text-fog-400 hover:text-fog-200">Full passage</summary>
            <p className="mt-1 whitespace-pre-wrap text-xs leading-relaxed text-fog-300">{s.text}</p>
          </details>
        </li>
      ))}
    </ol>
  );
}

export default function Chat({ documentIds, disabled }: { documentIds: string[] | null; disabled: boolean }) {
  const [turns, setTurns] = useState<Turn[]>([]);
  const [question, setQuestion] = useState('');
  const [busy, setBusy] = useState(false);
  const end = useRef<HTMLDivElement>(null);

  useEffect(() => end.current?.scrollIntoView?.({ behavior: 'smooth', block: 'end' }), [turns]);

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    const q = question.trim();
    if (q.length < 2 || busy) return;
    const id = Date.now();
    setTurns((t) => [...t, { id, question: q }]);
    setQuestion('');
    setBusy(true);
    try {
      const result = await ask(q, documentIds);
      setTurns((t) => t.map((x) => (x.id === id ? { ...x, result } : x)));
    } catch (err) {
      setTurns((t) => t.map((x) => (x.id === id ? { ...x, error: (err as Error).message } : x)));
    } finally {
      setBusy(false);
    }
  };

  return (
    <section className="panel flex min-h-[28rem] flex-col" aria-labelledby="chat-title">
      <h2 id="chat-title" className="panel-title">Ask your documents</h2>
      <div className="mt-3 flex-1 space-y-5 overflow-y-auto pr-1" aria-live="polite">
        {turns.length === 0 && (
          <p className="py-10 text-center text-sm text-fog-400">
            Try “How many days of sick leave do employees get?” after loading the samples.
          </p>
        )}
        {turns.map((t) => (
          <div key={t.id} className="space-y-2">
            <p className="flex items-start gap-2 text-sm text-fog-100">
              <User size={16} className="mt-0.5 shrink-0 text-fog-400" aria-hidden="true" />
              <span className="sr-only">You asked:</span> {t.question}
            </p>
            <div className="flex items-start gap-2">
              <Bot size={16} className="mt-0.5 shrink-0 text-accent-400" aria-hidden="true" />
              <div className="min-w-0 flex-1 text-sm">
                {!t.result && !t.error && (
                  <p className="flex items-center gap-2 text-fog-400" role="status">
                    <Loader2 size={14} className="animate-spin" aria-hidden="true" /> Searching…
                  </p>
                )}
                {t.error && <p role="alert" className="text-red-300">{t.error}</p>}
                {t.result && (
                  <>
                    {t.result.answer ? (
                      <div className="rounded-lg bg-ink-850 p-3">
                        <p className="whitespace-pre-wrap leading-relaxed text-fog-100">{t.result.answer}</p>
                        <p className="mt-2 text-xs text-fog-400">Answer generated by a local model ({t.result.model}) from the passages below. Check the sources.</p>
                      </div>
                    ) : t.result.found ? (
                      <p className="flex items-start gap-2 rounded-lg border border-ink-700 bg-ink-850/60 p-3 text-xs text-fog-300">
                        <FileSearch size={14} className="mt-0.5 shrink-0 text-accent-400" aria-hidden="true" />
                        <span>
                          <strong className="font-medium text-fog-100">Most relevant passages.</strong> {t.result.message}
                        </span>
                      </p>
                    ) : (
                      <p className="flex items-start gap-2 rounded-lg border border-amber-400/30 bg-amber-400/10 p-3 text-amber-100">
                        <Info size={14} className="mt-0.5 shrink-0" aria-hidden="true" /> {t.result.message}
                      </p>
                    )}
                    <Sources result={t.result} />
                    <p className="mt-2 text-[0.7rem] text-fog-400">Retrieval: {t.result.retrieval === 'hybrid' ? 'semantic + keyword (local embeddings)' : 'keyword (BM25)'}</p>
                  </>
                )}
              </div>
            </div>
          </div>
        ))}
        <div ref={end} />
      </div>
      <form onSubmit={submit} className="mt-4 flex gap-2">
        <label htmlFor="question" className="sr-only">Question</label>
        <input
          id="question"
          className="input"
          placeholder={disabled ? 'Add a ready document first' : 'Ask a question…'}
          value={question}
          disabled={disabled}
          maxLength={1000}
          enterKeyHint="send"
          onChange={(e) => setQuestion(e.target.value)}
        />
        <button type="submit" className="btn btn-primary shrink-0 px-3" disabled={disabled || busy || question.trim().length < 2} aria-label="Ask">
          <SendHorizonal size={16} aria-hidden="true" />
        </button>
      </form>
    </section>
  );
}
